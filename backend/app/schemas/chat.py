"""Pydantic schemas for user chat API request and response contracts."""

from typing import List, Literal, Optional
import uuid

from pydantic import BaseModel, Field, field_validator

from app.retrieval.models import SourceCitation


class ChatMessage(BaseModel):
    """A single turn in the conversation history."""

    role: Literal["user", "assistant"] = Field(description="Message author role: 'user' or 'assistant'")
    content: str = Field(min_length=1, max_length=4000, description="Message text content")


class ChatRequest(BaseModel):
    """User question and optional recent conversational context."""

    message: Optional[str] = Field(
        default=None,
        description="The student's natural-language question",
    )
    question: Optional[str] = Field(
        default=None,
        description="Alias for message for backwards compatibility with earlier client scaffolds",
    )
    history: Optional[List[ChatMessage]] = Field(
        default=None,
        max_length=10,
        description="Up to 10 recent conversation turns for context",
    )

    @field_validator("message", mode="before")
    @classmethod
    def resolve_message_or_question(cls, v: Optional[str], info) -> Optional[str]:
        # If message not provided but question is provided in values, will resolve in model_post_init
        return v

    def model_post_init(self, __context) -> None:
        if not self.message and self.question:
            self.message = self.question.strip()
        elif self.message:
            self.message = self.message.strip()

        if not self.message:
            raise ValueError("A valid question string must be provided in either 'message' or 'question'.")
        if len(self.message) > 2000:
            raise ValueError("Message exceeds maximum allowed length of 2000 characters.")


class ChatResponse(BaseModel):
    """Structured answer response containing citations and diagnostic retrieval metadata."""

    answer: str = Field(description="The grounded answer generated by the assistant")
    sources: List[SourceCitation] = Field(
        default_factory=list,
        description="List of cited source excerpts mapped to [1], [2] in answer",
    )
    retrieval_mode: str = Field(
        default="hybrid",
        description="Retrieval strategy applied: 'hybrid', 'dense_only', 'keyword_only', or 'none'",
    )
    request_id: Optional[str] = Field(
        default_factory=lambda: str(uuid.uuid4()),
        description="Unique request trace identifier",
    )

